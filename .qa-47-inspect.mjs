import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 2560, height: 1440 } });
const page = await context.newPage();
page.on('pageerror', error => console.log('PAGEERROR', error.message));
await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' });
console.log((await page.locator('body').innerText()).slice(0, 5000));
await page.getByRole('button', { name: 'Create Profile' }).first().click();
await page.waitForTimeout(250);
console.log('AFTER CREATE', (await page.locator('body').innerText()).slice(0, 3500));
await page.getByRole('textbox').fill('QA Miner');
await page.getByRole('button', { name: 'Begin', exact: true }).click();
await page.waitForTimeout(500);
console.log('GAME', (await page.locator('body').innerText()).slice(0, 6500));
await page.screenshot({ path: 'artifacts/qa/equipment-mining-generation-47/launch.png', fullPage: true });
await page.getByRole('button', { name: 'Start Mining', exact: true }).click();
const densityBefore = await page.locator('.mine-density-heading').innerText();
await page.waitForTimeout(2800);
const densityAfter = await page.locator('.mine-density-heading').innerText();
console.log('DENSITY', densityBefore, '=>', densityAfter);
await page.getByRole('button', { name: 'Equipment', exact: true }).click();
await page.waitForTimeout(250);
console.log('EQUIPMENT', (await page.locator('body').innerText()).slice(-3000));
await page.getByRole('button', { name: 'DEV', exact: true }).click();
await page.waitForTimeout(200);
console.log('DEVTOOLS', (await page.locator('body').innerText()).slice(-5000));
console.log('ITEM OPTIONS',JSON.stringify((await page.locator('select[aria-label="Dev grant item"] option').allTextContents()).filter(x=>x.includes('Copper'))));
await page.screenshot({ path: 'artifacts/qa/equipment-mining-generation-47/devtools.png', fullPage: true });
await browser.close();
